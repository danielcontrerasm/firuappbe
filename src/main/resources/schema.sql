-- Marketplace and transit tables. Older local databases may have the core
-- tracker tables but not these newer entities while Hibernate is in validate
-- mode, so keep their creation idempotent here.
CREATE TABLE IF NOT EXISTS dog_walker_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active boolean,
    approval_status varchar(255),
    availability varchar(1000),
    base_price numeric(10, 2),
    bio varchar(1500),
    created_at timestamp(6) with time zone,
    experience_years integer,
    neighborhood varchar(255),
    price_notes varchar(1000),
    services varchar(1000),
    updated_at timestamp(6) with time zone,
    user_id bigint NOT NULL UNIQUE,
    CONSTRAINT dog_walker_profiles_approval_status_check
        CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT dog_walker_profiles_user_fk FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS walk_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone,
    duration_minutes integer,
    notes varchar(2000),
    owner_budget numeric(10, 2),
    requested_start timestamp(6) without time zone,
    service_address varchar(1000),
    status varchar(255),
    updated_at timestamp(6) with time zone,
    walker_quoted_price numeric(10, 2),
    owner_id bigint NOT NULL,
    pet_id bigint,
    walker_profile_id bigint NOT NULL,
    CONSTRAINT walk_requests_status_check
        CHECK (status IN ('PENDING', 'NEGOTIATING', 'ACCEPTED', 'REJECTED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT walk_requests_owner_fk FOREIGN KEY (owner_id) REFERENCES users(id),
    CONSTRAINT walk_requests_pet_fk FOREIGN KEY (pet_id) REFERENCES pet(id),
    CONSTRAINT walk_requests_walker_fk FOREIGN KEY (walker_profile_id) REFERENCES dog_walker_profiles(id)
);

CREATE TABLE IF NOT EXISTS walk_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body varchar(2000) NOT NULL,
    created_at timestamp(6) with time zone,
