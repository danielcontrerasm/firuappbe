ALTER TABLE IF EXISTS geofence
    DROP CONSTRAINT IF EXISTS geofence_pet_id_key;
DROP INDEX IF EXISTS geofence_pet_id_key;

DO $$
DECLARE
    constraint_name text;
BEGIN
    IF to_regclass('public.geofence') IS NOT NULL THEN
        FOR constraint_name IN
            SELECT c.conname
            FROM pg_constraint c
            JOIN pg_attribute a ON a.attrelid = c.conrelid
                AND a.attnum = ANY(c.conkey)
            WHERE c.conrelid = 'public.geofence'::regclass
              AND c.contype = 'u'
              AND array_length(c.conkey, 1) = 1
              AND a.attname = 'pet_id'
        LOOP
            EXECUTE format('ALTER TABLE public.geofence DROP CONSTRAINT %I', constraint_name);
        END LOOP;
    END IF;
END $$;

